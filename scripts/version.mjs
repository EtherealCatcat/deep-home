#!/usr/bin/env node
// Single source of truth for the app version: package.json.
// `--sync` writes the derived files; `--check` verifies they match and is used by CI.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const mode = process.argv[2];
const VERSION_RE = /^\d+\.\d+\.\d+$/;

function fail(message) {
  console.error(message);
  process.exit(1);
}

function readJson(file) {
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    fail(`无法读取 ${file}：${error instanceof Error ? error.message : String(error)}`);
  }
}

if (mode !== "--sync" && mode !== "--check") {
  console.error("用法：node scripts/version.mjs --sync|--check");
  process.exit(2);
}

const pkg = readJson(join(root, "package.json"));
const version = pkg.version;
if (typeof version !== "string" || !VERSION_RE.test(version)) {
  fail(`package.json 的 version 必须是 x.y.z，当前为 ${JSON.stringify(version)}`);
}

const versionFile = join(root, "src/version.ts");
const versionSource = `// Generated by scripts/version.mjs --sync from package.json. Do not edit by hand.\nexport const APP_VERSION = "${version}";\n`;

const cargoFile = join(root, "src-tauri/Cargo.toml");
const cargo = readFileSync(cargoFile, "utf8");

function packageSection(text) {
  const start = text.indexOf("[package]");
  if (start < 0) return null;
  const rest = text.slice(start);
  const next = rest.slice(1).search(/^\[/m);
  return next < 0 ? rest : rest.slice(0, next + 1);
}

const cargoPackage = packageSection(cargo);
if (!cargoPackage) fail("src-tauri/Cargo.toml 缺少 [package] 段");
const cargoMatch = cargoPackage.match(/^version\s*=\s*"([^"]*)"/m);
if (!cargoMatch) fail("src-tauri/Cargo.toml 的 [package] 段缺少 version");

const tauriFile = join(root, "src-tauri/tauri.conf.json");
const tauri = readJson(tauriFile);

const expectedTauri = "../package.json";
const serverFile = join(root, "src/server.ts");
const server = readFileSync(serverFile, "utf8");
const webFile = join(root, "src/web.ts");
const web = readFileSync(webFile, "utf8");

function replaceCargoVersion(nextVersion) {
  const current = cargoPackage;
  const updated = current.replace(
    /^version\s*=\s*"[^"]*"/m,
    `version = "${nextVersion}"`,
  );
  return cargo.replace(current, updated);
}

const currentVersionSource = existsSync(versionFile) ? readFileSync(versionFile, "utf8") : null;

if (mode === "--sync") {
  if (currentVersionSource !== versionSource) {
    writeFileSync(versionFile, versionSource);
    console.log(`已更新 src/version.ts → ${version}`);
  }
  const nextCargo = replaceCargoVersion(version);
  if (nextCargo !== cargo) {
    writeFileSync(cargoFile, nextCargo);
    console.log(`已更新 src-tauri/Cargo.toml → ${version}`);
  }
  console.log(`版本 ${version} 已同步。`);
  process.exit(0);
}

const problems = [];

if (currentVersionSource === null) {
  problems.push("src/version.ts 不存在");
} else if (currentVersionSource !== versionSource) {
  problems.push(
    `src/version.ts 与 package.json 不一致：期望 ${JSON.stringify(versionSource.trim())}，实际 ${JSON.stringify(currentVersionSource.trim())}`,
  );
}

if (cargoMatch[1] !== version) {
  problems.push(
    `src-tauri/Cargo.toml 与 package.json 不一致：期望 ${JSON.stringify(version)}，实际 ${JSON.stringify(cargoMatch[1])}`,
  );
}

if (tauri.version !== expectedTauri) {
  problems.push(
    `src-tauri/tauri.conf.json 的 version 必须指向根 package.json：期望 ${JSON.stringify(expectedTauri)}，实际 ${JSON.stringify(tauri.version)}`,
  );
}

if (!server.includes('from "./version.js"') || /const\s+APP_VERSION\s*=/.test(server)) {
  problems.push("src/server.ts 必须从 ./version.js 导入 APP_VERSION，且不能再自己声明");
}

const webUsesTemplate = /"user-agent":\s*`[^`]*DeepHome\/\$\{APP_VERSION\}[^`]*`/.test(web);
if (!webUsesTemplate || /DeepHome\/\d/.test(web)) {
  problems.push("src/web.ts 的 User-Agent 必须用模板字符串写成 DeepHome/${APP_VERSION}，不能硬编码版本号");
}

if (problems.length) {
  for (const problem of problems) console.error(`✗ ${problem}`);
  console.error("运行 npm run version:sync 后再试。");
  process.exit(1);
}

console.log(`版本一致性检查通过：${version}`);
